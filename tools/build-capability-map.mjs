// The capability map: every JavaScript component UIkit registers, one line each.
// This is the payload that closes the measured gap — an agent that does not know a
// component exists rebuilds it by hand in CSS.
//
//   node build-capability-map.mjs <index.json> <uikit-site-checkout> <SKILL.md>
//
// The compact table is written into SKILL.md between the capability-map markers, so
// the always-loaded layer stays a single file and stays regenerable.
import fs from 'fs';
import path from 'path';

const [IX_PATH, SITE, SKILL] = process.argv.slice(2);
const IX = JSON.parse(fs.readFileSync(IX_PATH, 'utf8'));

// Purposes come from the docs pages themselves (<p class="uk-text-lead">), not from me.
const leads = {};
for (const f of fs.readdirSync(path.join(SITE, 'docs/pages')).filter((f) => f.endsWith('.md'))) {
  const m = fs.readFileSync(path.join(SITE, 'docs/pages', f), 'utf8')
    .match(/<p class="uk-text-lead">([\s\S]*?)<\/p>/);
  if (m) leads[f.replace(/\.md$/, '')] = m[1].replace(/\s+/g, ' ').trim().replace(/\.$/, '');
}

// components documented on a page with a different name
const PAGE = {
  'uk-drop': 'drop', 'uk-dropdown': 'dropdown', 'uk-dropnav': 'dropnav', 'uk-form-custom': 'form',
  'uk-height-match': 'height', 'uk-height-viewport': 'height', 'uk-height-placeholder': 'height',
  'uk-img': 'image', 'uk-overflow-auto': 'utility', 'uk-responsive': 'utility',
};
// Components with no docs page of their own, plus the handful whose page lead is
// generic ("a collection of useful utility classes") or shared by three components.
const HAND = {
  'uk-overflow-fade': 'fade the edges of a scrollable area to show there is more',
  'uk-scrollspy-nav': 'highlight the nav link whose section is in view',
  'uk-slider-parallax': 'move slide content at a different speed from the slide',
  'uk-slideshow-parallax': 'move slide content at a different speed from the slide',
  'uk-height-match': 'match the heights of elements that are not siblings',
  'uk-height-placeholder': 'hold the space of an element that will change height',
  'uk-height-viewport': 'size an element to the viewport, minus the navbar if asked',
  'uk-overflow-auto': 'make a child scroll instead of overflowing the viewport',
  'uk-responsive': 'keep an image or video inside its container',
  'uk-margin': 'add margin between elements as they wrap',
  'uk-img': 'lazy-load images and background images',
  'uk-video': 'autoplay, pause and lazy-load video, including YouTube',
  'uk-offcanvas': 'a sidebar that slides in over the page — mobile navigation',
  'uk-form-custom': 'replace a file input or select with your own markup',
  'uk-cover': 'expand an image or video to cover its container',
  'uk-navbar': 'the main site navigation bar, with dropdowns',
  'uk-grid': 'the responsive, nestable grid layout',
};
// one-icon shorthands — listed together rather than one row each
const ICON_SHORTHAND = ['uk-accordion-icon', 'uk-drop-parent-icon', 'uk-nav-parent-icon',
  'uk-navbar-parent-icon', 'uk-navbar-toggle-icon', 'uk-overlay-icon', 'uk-pagination-next',
  'uk-pagination-previous', 'uk-search-icon', 'uk-slidenav-next', 'uk-slidenav-previous',
  'uk-marker', 'uk-spinner', 'uk-totop', 'uk-close'];
// internals an author never writes directly
const INTERNAL = ['uk-lightbox-panel'];

const rows = [];
for (const [attr, def] of Object.entries(IX.components)) {
  if (ICON_SHORTHAND.includes(attr) || INTERNAL.includes(attr)) continue;
  const base = attr.replace(/^uk-/, '');
  let desc = HAND[attr] ?? leads[PAGE[attr] ?? base];
  if (!desc) { console.warn(`  no description for ${attr}`); continue; }
  // the docs lead sometimes trails into a second clause that adds nothing here
  desc = desc.split(/,\s+(?:which|like|and place|especially)\b/)[0].trim();
  rows.push({ attr, desc });
}
rows.sort((a, b) => a.attr.localeCompare(b.attr));

const out = [];
out.push(`Every attribute here is a real component in UIkit ${IX.version}. ` +
  '`show` prints any of their options.\n');
for (const r of rows) {
  out.push(`- \`${r.attr}\` — ${r.desc}`);
}
out.push(`\nOne-icon shorthands, no options: ${ICON_SHORTHAND.map((i) => `\`${i}\``).join(', ')}.`);

const table = out.join('\n');
const md = fs.readFileSync(SKILL, 'utf8');
const START = '<!-- BEGIN capability-map (generated by tools/build-capability-map.mjs — do not edit) -->';
const END = '<!-- END capability-map -->';
if (!md.includes(START) || !md.includes(END)) throw new Error('capability-map markers missing from SKILL.md');
const next = md.slice(0, md.indexOf(START) + START.length) + '\n' + table + '\n' + md.slice(md.indexOf(END));
fs.writeFileSync(SKILL, next);

const words = next.split(/\s+/).length;
console.log(`SKILL.md: ${rows.length} components in the map, ${Math.round(next.length / 4)} tokens ` +
  `(~${words} words) for the whole always-loaded layer`);
